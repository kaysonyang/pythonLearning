def get_hubei_store_ids(data):
    hubei_store_ids = []

    for area in data['data']:
        if area['areaName'] in provinces:
            for city in area.get('list', []):
                for district in city.get('list', []):
                    for store in district.get('storeList', []):
                        hubei_store_ids.append(store['storeId'])

    return hubei_store_ids


